package com.maheshclothes.file;

import com.maheshclothes.common.BusinessException;
import lombok.RequiredArgsConstructor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

/**
 * Uploaded images and receipts are kept in the database (table stored_files), not on the server's disk:
 * cloud containers lose local files on redeploy, and database backups then include every attachment.
 */
@Service
@RequiredArgsConstructor
public class FileService {

    public static final long MAX_IMAGE_BYTES = 2L * 1024 * 1024;
    public static final long MAX_DOCUMENT_BYTES = 5L * 1024 * 1024;
    private static final Set<String> IMAGE_TYPES = Set.of("image/png", "image/jpeg", "image/webp");
    private static final Set<String> DOCUMENT_TYPES = Set.of("image/png", "image/jpeg", "image/webp", "application/pdf");

    private final JdbcTemplate jdbc;

    public record StoredFile(UUID id, String fileName, String contentType, byte[] data) {
    }

    public UUID storeImage(MultipartFile f) {
        return store(f, IMAGE_TYPES, MAX_IMAGE_BYTES);
    }

    public UUID storeDocument(MultipartFile f) {
        return store(f, DOCUMENT_TYPES, MAX_DOCUMENT_BYTES);
    }

    private UUID store(MultipartFile f, Set<String> allowed, long maxBytes) {
        if (f == null || f.isEmpty()) {
            return null;
        }
        String type = f.getContentType() == null ? "" : f.getContentType().toLowerCase();
        if (!allowed.contains(type)) {
            throw new BusinessException("file.error.type");
        }
        if (f.getSize() > maxBytes) {
            throw new BusinessException("error.upload.size");
        }
        try {
            byte[] data = f.getBytes();
            if (!looksLike(type, data)) {
                throw new BusinessException("file.error.type");
            }
            String name = f.getOriginalFilename() == null ? "file" : f.getOriginalFilename().replaceAll("[^A-Za-z0-9._-]", "_");
            return save(name, type, data);
        } catch (IOException e) {
            throw new BusinessException("file.error.read");
        }
    }

    /** Stores bytes generated by the server itself (for example invoice PDFs). */
    public UUID save(String fileName, String contentType, byte[] data) {
        UUID id = UUID.randomUUID();
        jdbc.update("insert into stored_files (id, file_name, content_type, size_bytes, data, created_by) "
                        + "values (?, ?, ?, ?, ?, ?)", id, trim(fileName, 200), contentType, data.length, data,
                com.maheshclothes.security.CurrentUser.username());
        return id;
    }

    public Optional<StoredFile> load(UUID id) {
        return jdbc.query("select id, file_name, content_type, data from stored_files where id = ?",
                (rs, i) -> new StoredFile(rs.getObject(1, UUID.class), rs.getString(2), rs.getString(3), rs.getBytes(4)), id)
                .stream().findFirst();
    }

    /** Checks the first bytes so a renamed .exe cannot pass as an image. */
    static boolean looksLike(String type, byte[] d) {
        if (d.length < 12) {
            return false;
        }
        return switch (type) {
            case "image/png" -> (d[0] & 0xFF) == 0x89 && d[1] == 'P' && d[2] == 'N' && d[3] == 'G';
            case "image/jpeg" -> (d[0] & 0xFF) == 0xFF && (d[1] & 0xFF) == 0xD8;
            case "image/webp" -> d[0] == 'R' && d[1] == 'I' && d[2] == 'F' && d[3] == 'F' && d[8] == 'W' && d[9] == 'E';
            case "application/pdf" -> d[0] == '%' && d[1] == 'P' && d[2] == 'D' && d[3] == 'F';
            default -> false;
        };
    }

    private static String trim(String s, int max) {
        return s.length() <= max ? s : s.substring(0, max);
    }
}
